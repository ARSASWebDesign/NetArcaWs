/// <summary>Builds the reference catalog and compileable, typed invocation adapters from the pinned contracts.</summary>
public static class OperationDocumentation
{
    private static readonly XNamespace Wsdl = "http://schemas.xmlsoap.org/wsdl/";
    private static readonly XNamespace Xsd = "http://www.w3.org/2001/XMLSchema";
    private static readonly XNamespace Soap = "http://schemas.xmlsoap.org/wsdl/soap/";
    private static readonly (string File, string Contract, string Client, string Wsaa)[] Services =
    [
        ("wsfev1-production.wsdl", "WsfeV1", "Wsfev1Service", "wsfe"),
        ("wsfexv1-production.wsdl", "WsfexV1", "Wsfexv1Service", "wsfex"),
        ("wsmtxca-production.wsdl", "Wsmtxca", "Wsmtxcav1Service", "wsmtxca"),
        ("padron-a4-production.wsdl", "PadronA4", "PadronA4Service", "ws_sr_padron_a4"),
        ("padron-a5-production.wsdl", "PadronA5", "PadronA5Service", "ws_sr_constancia_inscripcion"),
        ("padron-a10-production.wsdl", "PadronA10", "PadronA10Service", "ws_sr_padron_a10"),
        ("padron-a13-production.wsdl", "PadronA13", "PadronA13Service", "ws_sr_padron_a13")
